#!/usr/bin/env python3
"""
Generate a C array holding the classic 8x16 VGA bitmap font.

The glyph data is read out of the bundled VGA BIOS ROM (docs/bios/vgabios.bin)
at build time, so it is never copied into the source tree.

    tools/mkfont.py docs/bios/vgabios.bin build/font8x16.c
"""
import sys

# The 8x16 bitmap of the letter 'A' as stored in the ROM font. Finding it
# tells us where the font table starts (256 glyphs x 16 bytes).
GLYPH_A = bytes([
    0x00, 0x00, 0x10, 0x38, 0x6C, 0xC6, 0xC6, 0xFE,
    0xC6, 0xC6, 0xC6, 0xC6, 0x00, 0x00, 0x00, 0x00,
])


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 1

    rom = open(sys.argv[1], "rb").read()
    pos = rom.find(GLYPH_A)
    if pos < 0:
        print("error: could not find the 8x16 font in the VGA BIOS")
        return 1

    base = pos - 0x41 * 16
    font = rom[base:base + 256 * 16]
    if len(font) != 4096:
        print("error: font table is truncated")
        return 1

    with open(sys.argv[2], "w") as out:
        out.write("/* Generated by tools/mkfont.py - do not edit. */\n")
        out.write("const unsigned char font8x16[4096] = {\n")
        for i in range(0, 4096, 16):
            row = ", ".join("0x%02x" % b for b in font[i:i + 16])
            out.write("    %s,\n" % row)
        out.write("};\n")

    print("  font8x16.c: 256 glyphs from %s" % sys.argv[1])
    return 0


if __name__ == "__main__":
    sys.exit(main())
